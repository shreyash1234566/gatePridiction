import json
from collections import defaultdict
from gate_apex_v10 import BestPredictor, build_data, MICRO_PRED_TH

with open("Q.json", "r", encoding="utf-8") as f:
    data = json.load(f)

processed_data = []
for q in data:
    processed_data.append({
        'subject': q['subject'],
        'topic': q['topic'],
        'micro': q['micro_topic'],
        'year': q['year'],
        'count_inc': 1.0
    })

train_q = [q for q in processed_data if q['year'] < 2026]
test_q = [q for q in processed_data if q['year'] == 2026]

pred = BestPredictor()
act_topic = defaultdict(float)
for q in test_q: 
    act_topic[f"{q['subject']}::{q['topic']}"] += 1
    
topic_preds = [{'subject': k.split('::')[0], 'topic': k.split('::')[1], 'predicted_count': v} for k,v in act_topic.items()]
pred.topic_data, pred.micro_data = build_data(train_q)
pred.learn_micro_tau_per_subject(pred.micro_data, [2026])
micro_preds = pred.predict_micro(topic_preds, 2026)

pred_micro = defaultdict(float)
concept_to_raw_counts = defaultdict(lambda: defaultdict(float))
for q in train_q:
    concept = pred._get_canonical_concept(q['subject'], q['topic'], q['micro'])
    pk = f"{q['subject']}::{q['topic']}"
    ck = f"{pk}::{concept}"
    concept_to_raw_counts[ck][f"{pk}::{q['micro']}"] += 1.0

for m in micro_preds:
    concept = m.get('canonical_concept', m['micro_topic'])
    pk = f"{m['subject']}::{m['topic']}"
    ck = f"{pk}::{concept}"
    
    raw_counts = concept_to_raw_counts.get(ck, {})
    if raw_counts:
        total_raw = sum(raw_counts.values())
        for raw_key, cnt in raw_counts.items():
            frac = cnt / total_raw
            pred_micro[raw_key] += m['predicted_count'] * frac
    else:
        pred_micro[ck] += m['predicted_count']

above_thresh = [k for k, v in pred_micro.items() if v >= MICRO_PRED_TH]
print(f'Total raw MTs generated by expansion: {len(pred_micro)}')
print(f'Total raw MTs evaluated as hits (score >= {MICRO_PRED_TH}): {len(above_thresh)}')
